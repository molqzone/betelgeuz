fn gen_ts(check: bool) {
    let schemas = protocol_schemas();
    validate_method_contracts(&schemas);
    let mut content = String::from(
        "// Generated by `cargo xtask gen-ts` from protocol and strategy schemas. Do not edit by hand.\n\n",
    );
    for (_, schema) in schemas {
        let schema = serde_json::to_value(schema).expect("schema converts to JSON");
        content.push_str(&typescript_schema(&schema));
        content.push('\n');
    }
    for (id, schema) in strategy::builtin_config_schemas() {
        content.push_str(&format!("// Strategy configuration: {id}\n"));
        content.push_str(&typescript_schema(&schema));
        content.push('\n');
    }

    content.push_str(&format!(
        "export const PROTOCOL_VERSION = {};\nexport const MAX_MESSAGE_BYTES = {};\n\n",
        serde_json::to_string(protocol::PROTOCOL_VERSION).unwrap(),
        protocol::MAX_MESSAGE_BYTES
    ));
    content.push_str("export const REQUEST_METHODS = [\n");
    for contract in protocol::methods::METHOD_CONTRACTS {
        content.push_str(&format!(
            "  {},\n",
            serde_json::to_string(contract.method).unwrap()
        ));
    }
    content
        .push_str("] as const;\n\nexport type RequestMethod = typeof REQUEST_METHODS[number];\n\n");

    content.push_str("export const NOTIFICATION_METHODS = [\n");
    for contract in protocol::methods::NOTIFICATION_CONTRACTS {
        content.push_str(&format!(
            "  {},\n",
            serde_json::to_string(contract.method).unwrap()
        ));
    }
    content.push_str(
        "] as const;\n\nexport type NotificationMethod = typeof NOTIFICATION_METHODS[number];\n\n",
    );

    content.push_str("export type RpcRequestParams = {\n");
    for contract in protocol::methods::METHOD_CONTRACTS {
        content.push_str(&format!(
            "  {}: {};\n",
            serde_json::to_string(contract.method).unwrap(),
            contract.params
        ));
    }
    content.push_str("};\n\nexport type RpcRequestResults = {\n");
    for contract in protocol::methods::METHOD_CONTRACTS {
        let result = contract.result.unwrap_or("never");
        content.push_str(&format!(
            "  {}: {};\n",
            serde_json::to_string(contract.method).unwrap(),
            if result == "null" { "null" } else { result }
        ));
    }
    content.push_str("};\n\nexport type RpcNotificationParams = {\n");
    for contract in protocol::methods::NOTIFICATION_CONTRACTS {
        content.push_str(&format!(
            "  {}: {};\n",
            serde_json::to_string(contract.method).unwrap(),
            contract.params
        ));
    }
    content.push_str("};\n");

    let path = workspace_root()
        .join("editors")
        .join("code")
        .join("src")
        .join("protocol.ts");
    write_generated(&path, &content, check);
    if check {
        println!("TypeScript protocol types are current");
    } else {
        println!("wrote {}", path.display());
    }
}

fn typescript_schema(schema: &serde_json::Value) -> String {
    let root_name = schema
        .get("title")
        .and_then(serde_json::Value::as_str)
        .map(type_identifier)
        .unwrap_or_else(|| "ProtocolType".into());
    let mut out = String::new();
    if let Some(definitions) = schema.get("$defs").and_then(serde_json::Value::as_object) {
        for (name, definition) in definitions {
            let local_name = format!("{root_name}_{}", type_identifier(name));
            out.push_str(&format!(
                "type {local_name} = {};\n",
                schema_type(definition, &root_name)
            ));
        }
    }
    out.push_str(&format!(
        "export type {root_name} = {};\n",
        schema_type(schema, &root_name)
    ));
    out
}

fn schema_type(schema: &serde_json::Value, scope: &str) -> String {
    use serde_json::Value;

    if let Some(reference) = schema.get("$ref").and_then(Value::as_str) {
        if let Some(name) = reference.strip_prefix("#/$defs/") {
            return format!("{scope}_{}", type_identifier(name));
        }
        return "unknown".into();
    }
    for key in ["oneOf", "anyOf", "allOf"] {
        if let Some(variants) = schema.get(key).and_then(Value::as_array) {
            let separator = if key == "allOf" { " & " } else { " | " };
            return variants
                .iter()
                .map(|variant| schema_type(variant, scope))
                .collect::<Vec<_>>()
                .join(separator);
        }
    }
    if let Some(value) = schema.get("const") {
        return serde_json::to_string(value).unwrap();
    }
    if let Some(values) = schema.get("enum").and_then(Value::as_array) {
        return values
            .iter()
            .map(|value| serde_json::to_string(value).unwrap())
            .collect::<Vec<_>>()
            .join(" | ");
    }
    if let Some(types) = schema.get("type").and_then(Value::as_array) {
        let variants = types
            .iter()
            .filter_map(Value::as_str)
            .map(|kind| {
                let mut branch = schema.clone();
                branch["type"] = Value::String(kind.to_owned());
                schema_type(&branch, scope)
            })
            .collect::<Vec<_>>();
        return variants.join(" | ");
    }

    match schema.get("type").and_then(Value::as_str) {
        Some("object") => {
            if let Some(properties) = schema.get("properties").and_then(Value::as_object) {
                let required: std::collections::HashSet<_> = schema
                    .get("required")
                    .and_then(Value::as_array)
                    .into_iter()
                    .flatten()
                    .filter_map(Value::as_str)
                    .collect();
                let mut fields = String::from("{\n");
                for (name, property) in properties {
                    let optional = if required.contains(name.as_str()) {
                        ""
                    } else {
                        "?"
                    };
                    fields.push_str(&format!(
                        "  {}{optional}: {};\n",
                        serde_json::to_string(name).unwrap(),
                        schema_type(property, scope)
                    ));
                }
                fields.push('}');
                fields
            } else if let Some(additional) = schema.get("additionalProperties") {
                if additional == false {
                    "Record<string, never>".into()
                } else if additional == true {
                    "Record<string, unknown>".into()
                } else {
                    format!("Record<string, {}>", schema_type(additional, scope))
                }
            } else {
                "Record<string, unknown>".into()
            }
        }
        Some("array") => {
            let item = schema
                .get("items")
                .map(|item| schema_type(item, scope))
                .unwrap_or_else(|| "unknown".into());
            format!("Array<{item}>")
        }
        Some("string") => "string".into(),
        Some("integer" | "number") => "number".into(),
        Some("boolean") => "boolean".into(),
        Some("null") => "null".into(),
        _ => "unknown".into(),
    }
}

fn type_identifier(value: &str) -> String {
    let mut result = String::new();
    for segment in value.split(|character: char| !character.is_ascii_alphanumeric()) {
        if segment.is_empty() {
            continue;
        }
        let mut characters = segment.chars();
        if let Some(first) = characters.next() {
            result.extend(first.to_uppercase());
            result.extend(characters);
        }
    }
    if result.is_empty() || result.chars().next().is_some_and(|ch| ch.is_ascii_digit()) {
        format!("Type{result}")
    } else {
        result
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn typescript_generation_preserves_nullability_and_schema_references() {
        let schema = json!({
            "title": "Example",
            "$defs": { "Record": { "type": "object", "properties": { "ok": { "type": "boolean" } }, "required": ["ok"] } },
            "type": "object",
            "properties": {
                "value": { "type": ["string", "null"] },
                "record": { "$ref": "#/$defs/Record" }
            },
            "required": ["record"]
        });

        let output = typescript_schema(&schema);
        assert!(output.contains("type Example_Record ="));
        assert!(output.contains("\"value\"?: string | null;"));
        assert!(output.contains("\"record\": Example_Record;"));
        assert!(!output.contains("string | unknown"));
    }
}

fn validate_method_contracts(schemas: &[(&str, schemars::Schema)]) {
    let names: std::collections::HashSet<_> = schemas.iter().map(|(name, _)| *name).collect();
    for contract in protocol::methods::METHOD_CONTRACTS {
        assert!(
            names.contains(type_schema_name(contract.params).as_str()),
            "no JSON schema registered for {} params `{}`",
            contract.method,
            contract.params
        );
        if let Some(result) = contract.result.filter(|result| *result != "null") {
            assert!(
                names.contains(type_schema_name(result).as_str()),
                "no JSON schema registered for {} result `{result}`",
                contract.method
            );
        }
    }
    for contract in protocol::methods::NOTIFICATION_CONTRACTS {
        assert!(
            names.contains(type_schema_name(contract.params).as_str()),
            "no JSON schema registered for {} params `{}`",
            contract.method,
            contract.params
        );
    }
}

fn type_schema_name(type_name: &str) -> String {
    let mut result = String::new();
    for (index, character) in type_name.chars().enumerate() {
        if character.is_ascii_uppercase() && index > 0 {
            result.push('-');
        }
        result.push(character.to_ascii_lowercase());
    }
    result
}

fn write_generated(path: &std::path::Path, content: &str, check: bool) {
    if check {
        let existing = std::fs::read_to_string(path).unwrap_or_else(|error| {
            panic!("cannot read generated file {}: {error}", path.display())
        });
        assert_eq!(
            existing,
            content,
            "generated file is stale: {}",
            path.display()
        );
    } else {
        std::fs::write(path, content).unwrap_or_else(|error| {
            panic!("cannot write generated file {}: {error}", path.display())
        });
    }
}

/// `docs/ERRORS.md` from the common and strategy-owned catalogs. Never hand-edited.
fn gen_errors(check: bool) {
    use errors::{ErrorCatalogEntry, ErrorCode};
    use std::collections::HashSet;

    let mut out = String::new();
    out.push_str("# Error catalog\n\n");
    out.push_str(
        "Generated by `cargo xtask gen-errors` from core and strategy error definitions. Do not edit by hand. Remediation values are stable action identifiers for frontend presentation.\n\n",
    );
    out.push_str("| code | phase | meaning | remediation action | retriable |\n");
    out.push_str("| --- | --- | --- | --- | --- |\n");
    let mut catalog: Vec<ErrorCatalogEntry> = ErrorCode::ALL
        .into_iter()
        .map(|code| ErrorCatalogEntry {
            code: code.code(),
            definition: code.def(),
        })
        .collect();
    catalog.extend_from_slice(strategy::ERROR_CATALOG);
    let mut seen = HashSet::new();
    for entry in catalog {
        assert!(
            seen.insert(entry.code),
            "duplicate error code: {}",
            entry.code
        );
        let def = entry.definition;
        let phase = def.phase.map(|p| p.as_str()).unwrap_or("any");
        let retriable = if def.retriable { "yes" } else { "no" };
        out.push_str(&format!(
            "| `{}` | {} | {} | `{}` | {} |\n",
            entry.code, phase, def.summary, def.remediation, retriable
        ));
    }

    let path = workspace_root().join("docs").join("ERRORS.md");
    write_generated(&path, &out, check);
    if check {
        println!("error catalog is current");
    } else {
        println!("wrote {}", path.display());
    }
}

fn todo_task(name: &str) -> ! {
    eprintln!("xtask {name}: not implemented yet (Phase 0)");
    std::process::exit(1);
}
