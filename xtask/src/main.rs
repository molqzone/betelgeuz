//! `cargo xtask` — codegen and packaging, keeping every generated artifact
//! derived from their owning crates instead of hand-maintained.

use std::path::PathBuf;

fn main() {
    let mut args = std::env::args().skip(1);
    let task = args.next().unwrap_or_default();
    let check_generated = args.any(|arg| arg == "--check");
    match task.as_str() {
        // JSON Schema for the protocol, configuration keys, and descriptor.
        "gen-schema" => gen_schema(check_generated),
        // docs/ERRORS.md from common and strategy error definitions.
        "gen-errors" => gen_errors(check_generated),
        // TypeScript types for the VS Code adapter from the protocol schemas.
        "gen-ts" => gen_ts(check_generated),
        // Build core binaries and assemble the extension VSIX.
        "package" => todo_task("package"),
        _ => {
            eprintln!("usage: cargo xtask <gen-schema|gen-errors|gen-ts|package>");
            std::process::exit(2);
        }
    }
}

fn workspace_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("xtask lives at the workspace root")
        .to_path_buf()
}

/// JSON Schema and protocol reference derived from the protocol crate.
fn gen_schema(check: bool) {
    let root = workspace_root();
    let schema_dir = root.join("target").join("schema").join("protocol");
    std::fs::create_dir_all(&schema_dir).expect("create protocol schema directory");
    let schemas = protocol_schemas();
    validate_method_contracts(&schemas);
    for (name, schema) in &schemas {
        let path = schema_dir.join(format!("{name}.json"));
        let content = format!(
            "{}\n",
            serde_json::to_string_pretty(schema).expect("schema serializes")
        );
        write_generated(&path, &content, false);
    }

    let strategy_schema_dir = root.join("target").join("schema").join("strategies");
    std::fs::create_dir_all(&strategy_schema_dir).expect("create strategy schema directory");
    let strategy_schemas = strategy::builtin_config_schemas();
    for (id, schema) in &strategy_schemas {
        let path = strategy_schema_dir.join(format!("{id}.json"));
        let content = format!("{}\n", serde_json::to_string_pretty(schema).unwrap());
        write_generated(&path, &content, false);
    }

    let mut doc = String::from(
        "# Protocol reference\n\nGenerated by `cargo xtask gen-schema` from protocol and strategy contracts. Do not edit by hand.\n\n",
    );
    doc.push_str(&format!(
        "Protocol version: `{}`. Framing: JSON-RPC 2.0 with LSP-style `Content-Length` headers over stdio.\n\n",
        protocol::PROTOCOL_VERSION
    ));
    doc.push_str(&format!(
        "The maximum JSON body size is `{}` bytes. Artifact contents stay on the host; the artifact record carries a local path, target name, configuration, size, content hash, and optional symbols path; the core opens that path and streams it over SFTP.\n\n",
        protocol::MAX_MESSAGE_BYTES
    ));

    doc.push_str("## Requests\n\n| Method | Params | Result |\n| --- | --- | --- |\n");
    for contract in protocol::methods::METHOD_CONTRACTS {
        let result = contract.result.unwrap_or("none");
        doc.push_str(&format!(
            "| `{}` | `{}` | `{}` |\n",
            contract.method, contract.params, result
        ));
    }
    doc.push_str("\n## Notifications\n\n| Method | Params |\n| --- | --- |\n");
    for contract in protocol::methods::NOTIFICATION_CONTRACTS {
        doc.push_str(&format!(
            "| `{}` | `{}` |\n",
            contract.method, contract.params
        ));
    }
    doc.push_str("\n## Configuration keys\n\n| Key |\n| --- |\n");
    for key in protocol::config::FIXED_KEYS {
        doc.push_str(&format!("| `{key}` |\n"));
    }
    doc.push_str("\nPattern prefixes:\n\n");
    for pattern in protocol::config::KEY_PATTERNS {
        doc.push_str(&format!("- `{pattern}`\n"));
    }
    doc.push_str("\n## Strategy configuration\n\n");
    for key in strategy::CONFIG_KEYS {
        let full_key = protocol::config::strategy_key(key.strategy_id, key.name);
        doc.push_str(&format!("- `{full_key}`\n"));
    }
    doc.push_str("\nGenerated JSON Schemas are build artifacts under `target/schema/`, published only when a third-party frontend consumes them.\n");

    let doc_path = root.join("docs").join("protocol.md");
    write_generated(&doc_path, &doc, check);
    if check {
        println!("protocol schemas and reference are current");
    } else {
        println!(
            "wrote {} protocol schemas, {} strategy schemas, and {}",
            schemas.len(),
            strategy_schemas.len(),
            doc_path.display()
        );
    }
}

